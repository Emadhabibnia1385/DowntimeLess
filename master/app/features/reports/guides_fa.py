"""Fix guides in Persian for a person who has no AI assistant, one per issue code the master raises.

Each guide says what the issue means, why it matters, how to check, what to run and how to know it is fixed.
Commands are copied unchanged from the English playbook (a test holds that) and are only shown: the panel never runs
them. Checks are read-only; fixes change the server, so they are for the owner to run by hand.
"""
from typing import Any, Dict, List, Optional, Sequence, Tuple, Union

Step = Union[str, Tuple[str, str]]


def _steps(items: Sequence[Step]) -> List[Dict[str, Optional[str]]]:
    out = []
    for item in items:
        text, cmd = (item, None) if isinstance(item, str) else item
        out.append({"text": text, "cmd": cmd})
    return out


def _g(code: str, title: str, meaning: str, why: str, checks: Sequence[Step], fixes: Sequence[Step],
       fixed: Sequence[str], never: Sequence[str]) -> Dict[str, Any]:
    return {
        "code": code, "title": title, "meaning": meaning, "why": why, "checks": _steps(checks), "fixes": _steps(fixes),
        "fixed_when": list(fixed), "never": list(never),
    }


